import "server-only";
import {
  Document,
  Page,
  View,
  Text,
  StyleSheet,
  renderToBuffer,
} from "@react-pdf/renderer";
import type { PartnerProgramApplicationRow } from "@/lib/admin-stats";

const styles = StyleSheet.create({
  page: { padding: 28, fontSize: 8, fontFamily: "Helvetica" },
  title: { fontSize: 14, fontWeight: 700, color: "#1d4ed8", marginBottom: 2 },
  subtitle: { fontSize: 8, color: "#555", marginBottom: 10 },
  summaryRow: { flexDirection: "row", marginBottom: 10 },
  summaryPill: {
    backgroundColor: "#f1f5f9",
    borderRadius: 4,
    paddingVertical: 3,
    paddingHorizontal: 8,
    marginRight: 8,
    fontSize: 7.5,
    color: "#1d4ed8",
  },
  table: { border: "1 solid #e2e8f0" },
  headerRow: { flexDirection: "row", backgroundColor: "#1d4ed8" },
  row: { flexDirection: "row", borderTop: "1 solid #e2e8f0" },
  rowAlt: { backgroundColor: "#f8fafc" },
  th: { color: "#fff", fontSize: 7, fontWeight: 700, padding: 3 },
  td: { fontSize: 7, color: "#111", padding: 3 },
  colNo: { width: "4%" },
  colTime: { width: "10%" },
  colName: { width: "16%" },
  colType: { width: "9%" },
  colStatus: { width: "9%" },
  colMobile: { width: "11%" },
  colEmail: { width: "18%" },
  colReferred: { width: "13%" },
  colCollege: { width: "10%" },
  footer: { marginTop: 10, fontSize: 7, color: "#94a3b8" },
});

function fmtTimeIst(iso: string) {
  return new Date(iso).toLocaleString("en-IN", {
    timeZone: "Asia/Kolkata",
    day: "2-digit",
    month: "short",
    hour: "numeric",
    minute: "2-digit",
    hour12: true,
  });
}

export interface PartnerProgramApplicationsPdfData {
  title: string;
  subtitle: string;
  totalCount: number;
  partnerCount: number;
  coPartnerCount: number;
  approvedCount: number;
  pendingCount: number;
  rejectedCount: number;
  applications: PartnerProgramApplicationRow[];
}

function PartnerProgramApplicationsDocument({
  data,
}: {
  data: PartnerProgramApplicationsPdfData;
}) {
  return (
    <Document>
      <Page size="A4" orientation="landscape" style={styles.page}>
        <Text style={styles.title}>{data.title}</Text>
        <Text style={styles.subtitle}>{data.subtitle}</Text>

        <View style={styles.summaryRow}>
          <Text style={styles.summaryPill}>Total: {data.totalCount}</Text>
          <Text style={styles.summaryPill}>Partner: {data.partnerCount}</Text>
          <Text style={styles.summaryPill}>Co-Partner: {data.coPartnerCount}</Text>
          <Text style={styles.summaryPill}>Approved: {data.approvedCount}</Text>
          <Text style={styles.summaryPill}>Pending: {data.pendingCount}</Text>
          <Text style={styles.summaryPill}>Rejected: {data.rejectedCount}</Text>
        </View>

        <View style={styles.table}>
          <View style={styles.headerRow} fixed>
            <Text style={[styles.colNo, styles.th]}>#</Text>
            <Text style={[styles.colTime, styles.th]}>Time (IST)</Text>
            <Text style={[styles.colName, styles.th]}>Name</Text>
            <Text style={[styles.colType, styles.th]}>Type</Text>
            <Text style={[styles.colStatus, styles.th]}>Status</Text>
            <Text style={[styles.colMobile, styles.th]}>Mobile</Text>
            <Text style={[styles.colEmail, styles.th]}>Email</Text>
            <Text style={[styles.colReferred, styles.th]}>Referred by</Text>
            <Text style={[styles.colCollege, styles.th]}>College</Text>
          </View>
          {data.applications.map((a, i) => (
            <View
              key={a.id}
              style={i % 2 === 1 ? [styles.row, styles.rowAlt] : styles.row}
              wrap={false}
            >
              <Text style={[styles.colNo, styles.td]}>{i + 1}</Text>
              <Text style={[styles.colTime, styles.td]}>{fmtTimeIst(a.createdAt)}</Text>
              <Text style={[styles.colName, styles.td]}>{a.name}</Text>
              <Text style={[styles.colType, styles.td]}>
                {a.partnerType === "campus" ? "Partner" : "Co-Partner"}
              </Text>
              <Text style={[styles.colStatus, styles.td]}>{a.status}</Text>
              <Text style={[styles.colMobile, styles.td]}>{a.mobile}</Text>
              <Text style={[styles.colEmail, styles.td]}>{a.email ?? "-"}</Text>
              <Text style={[styles.colReferred, styles.td]}>{a.referredBy ?? "-"}</Text>
              <Text style={[styles.colCollege, styles.td]}>{a.collegeName ?? "-"}</Text>
            </View>
          ))}
        </View>

        <Text style={styles.footer}>
          Generated by YUVAN for internal admin use — Yuva Champions Cricket
          Partner Program. Contains personal contact details — handle
          accordingly.
        </Text>
      </Page>
    </Document>
  );
}

export async function renderPartnerProgramApplicationsPdf(
  data: PartnerProgramApplicationsPdfData,
): Promise<Buffer> {
  return renderToBuffer(<PartnerProgramApplicationsDocument data={data} />);
}
